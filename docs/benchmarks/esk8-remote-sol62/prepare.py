"""Prepare a source-free full remote schematic trial for one Codex model."""
from pathlib import Path
import hashlib, json, shutil, subprocess, sys

base = Path(__file__).resolve().parent
root = base / "sol"
model, effort, deadline_s, max_turns = "gpt-6.2-sol", "medium", 1800, 120
binary = Path("/home/okhsunrog/code/rust/foilfern/target/release/foilfern-mcp")
repo = binary.parents[2]
previous = Path("/home/okhsunrog/tmp_zfs/codex_tmp/foilfern-remote-schematic-after-groups")
snapshot = Path("/home/okhsunrog/tmp_zfs/codex_tmp/foilfern-remote-schematic-acp/workspace")

head = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=repo, text=True).strip()
info = json.loads(subprocess.check_output([str(binary), "call", "server_info", "{}"]))["response"]["structuredContent"]["result"]
assert info["build"]["source_commit"] == head, (info["build"], head)
assert info["build"]["tracked_source_state"] == "clean"
assert info["build"]["cargo_profile"] == "release"
catalog = json.loads(subprocess.check_output([str(binary), "tools"]))

if root.exists():
    sys.exit(f"{root} exists; remove it to prepare a fresh trial")
for sub in ["bin", "case/work", "tmp", "uv-cache", "codex-state"]:
    (root / sub).mkdir(parents=True)
shutil.copy2(binary, root / "bin/foilfern-mcp")
shutil.copytree(snapshot, root / "workspace")
calls = [
    {"tool": "project_create", "arguments": {"name": "Esk8 Remote", "directory": str(root / "case/project"), "author": "okhsunrog", "create_board": False}},
    {"tool": "project_save"},
]
subprocess.run([str(root / "bin/foilfern-mcp"), "--workspace", str(root / "workspace"), "batch", "-"], input=json.dumps(calls), text=True, check=True, stdout=subprocess.DEVNULL)
shutil.copy2(Path.home() / ".codex/auth.json", root / "codex-state/auth.json")
(root / "codex-state/auth.json").chmod(0o600)
(root / "tools.json").write_text(json.dumps(catalog, indent=2) + "\n")
for name in ["pyproject.toml", "uv.lock"]:
    shutil.copy2(previous / name, root / name)

# Same task text as the interrupted DeepSeek trial; only paths, limits and the
# catalog generated by the current binary change.
old = (previous / "case/prompt.txt").read_text()
task = old[: old.index("SERVER STARTING INSTRUCTIONS")]
task = task.replace(str(previous), str(root))
task = task.replace("up to 180 model turns and a 45-minute session deadline", f"up to {max_turns} model turns and a {deadline_s // 60}-minute session deadline")
assert f"{deadline_s // 60}-minute" in task and str(previous) not in task
prompt = task + "SERVER STARTING INSTRUCTIONS\n" + catalog["instructions"] + "\n\nFULL TOOL CATALOG\n"
prompt += "\n\n".join(f"## {t['name']}\n\n{t.get('description', '')}" for t in catalog["tools"])
(root / "case/prompt.txt").write_text(prompt)
fixture = {
    "model": model, "reasoning_effort": effort, "client": subprocess.check_output(["codex", "--version"], text=True).strip(),
    "source_access": False, "binary": info, "sha256": hashlib.sha256(binary.read_bytes()).hexdigest(),
    "normalized_prompt_sha256": hashlib.sha256(prompt.replace(str(root), "@ROOT@").encode()).hexdigest(),
    "catalog_tools": len(catalog["tools"]), "cpu_affinity": [0, 1], "deadline_s": deadline_s,
    "max_model_turns": max_turns, "scenario": "esk8_remote_full",
}
(root / "case/fixture.json").write_text(json.dumps(fixture, indent=2) + "\n")
print(json.dumps({k: fixture[k] for k in ["model", "reasoning_effort", "sha256", "catalog_tools", "deadline_s"]}))
